%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% function:    libCZon_Lift(Z);                                           %
% Description: Computes lifted zonotope ZL for constrained zonotope Z.    %
% Input:       Z      - constrained zonotope                              %                                        %
% Output:      ZL     - Lifted zonotope                                   %
%              flag   - status flag. Zero if successful.                  %
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

function [ZL, flag] = libCZon_Lift(Z)

    %---------------------------------------------------------%
    %Initialize
    flag  = 0; ZL=cell(4,1);
    %---------------------------------------------------------%


    
    %---------------------------------------------------------%
    %Check inputs
    nc = size( Z{3} , 1 );
    if (nc<=0); ZL=Z; return; end;
    %---------------------------------------------------------%
    
    
    
    %---------------------------------------------------------%
    %Construct Lifted Zonotope
    ZL{1} = [ Z{1}; -Z{4} ];
    ZL{2} = [ Z{2};  Z{3} ];
    %---------------------------------------------------------%
  
end
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
% End libCZon_Lift                                                        %
